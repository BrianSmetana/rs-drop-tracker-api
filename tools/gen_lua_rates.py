"""Generate plugin/drop_tracker_rs/rates.lua from rare_drops.json (+ tools/clog_extra_rates.json).

The in-game plugin shows percentages on the boss collection log, which needs the per-kill drop rate of
each item. Only flat-rate items are exported from rare_drops.json: items whose chance depends on enrage,
killstreak or bad-luck mitigation are skipped because the plugin cannot score them locally.
tools/clog_extra_rates.json adds display-only rates (pets, set pieces, tertiaries) the allowlist lacks.
The rates themselves are built by app/clog_rates.py, which the backend also uses, so the two stay identical.

    python tools/gen_lua_rates.py
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.clog_rates import NO_LABELS, SHARED_DROPS, load, strategy_overlays  # noqa: E402,F401  (NO_LABELS: pages with no percentages)

SRC = ROOT / "rare_drops.json"
EXTRA = ROOT / "tools" / "clog_extra_rates.json"
OUT = ROOT / "plugin" / "drop_tracker_rs" / "rates.lua"


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def lua_rate(rate):
    if isinstance(rate, dict) and "rolls" in rate:
        return f"{{ rate = {rate['rate']!r}, rolls = {rate['rolls']} }}"
    if isinstance(rate, dict):
        hard = f", hard_base = {rate['hard_base']!r}" if "hard_base" in rate else ""
        return f"{{ base = {rate['base']!r}, threshold = {rate['threshold']}{hard} }}"
    return repr(rate)


def main():
    rates, aliases = load(SRC, EXTRA)
    flat_only, _ = load(SRC, None)
    kept = sum(len(v) for v in flat_only.values())
    extra_count = sum(len(v) for v in rates.values()) - kept

    lines = [
        "-- Generated by tools/gen_lua_rates.py from rare_drops.json and tools/clog_extra_rates.json. Do not edit by hand.",
        "-- rates[boss][item] = chance per kill, or { base = 1/D, threshold = T } for boss pets (the chance steps up",
        "-- by base every T total kills, capped at 10x; hard_base is the per-kill base in hard mode);",
        "-- { rate = p, rolls = r } is r independent rolls of chance p per kill; aliases[name] = canonical boss.",
        "-- shared[item] = bosses that all drop it: the item is scored over their kills added together.",
        "-- strategies[group] = enrage bosses: how the player farms them (an enrage and killstreak per option); an option's",
        "-- rates are laid over the base rates of those pages while it is selected.",
        "return {",
        "  rates = {",
    ]
    for boss in sorted(rates):
        entries = [f"[{lua_str(item)}] = {lua_rate(rate)}" for item, rate in sorted(rates[boss].items())]
        lines.append(f"    [{lua_str(boss)}] = {{ " + ", ".join(entries) + " },")
    lines += ["  },", "  aliases = {"]
    for name, canon in sorted(aliases.items()):
        lines.append(f"    [{lua_str(name)}] = {lua_str(canon)},")
    lines += ["  },", "  shared = {"]
    for item, bosses in sorted(SHARED_DROPS.items()):
        lines.append(f"    [{lua_str(item)}] = {{ " + ", ".join(lua_str(b) for b in bosses) + " },")
    lines += ["  },", "  strategies = {"]
    for group, strat in sorted(strategy_overlays(SRC).items()):
        lines.append(f"    [{lua_str(group)}] = {{ default = {lua_str(strat['default'])}, options = {{")
        for opt in strat["options"]:
            pages = []
            for page, items in sorted(opt["rates"].items()):
                entries = ", ".join(f"[{lua_str(i)}] = {lua_rate(r)}" for i, r in sorted(items.items()))
                pages.append(f"[{lua_str(page)}] = {{ {entries} }}")
            lines.append(f"      {{ id = {lua_str(opt['id'])}, label = {lua_str(opt['label'])}, "
                         f"rates = {{ {', '.join(pages)} }} }},")
        lines.append("    } },")
    lines += ["  },", "}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {kept} items from rare_drops.json, {extra_count} extra")


if __name__ == "__main__":
    main()
