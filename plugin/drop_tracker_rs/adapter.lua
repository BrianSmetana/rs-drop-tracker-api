-- Binds core.lua to the public RS client API (developer.runescape.com/rs).
-- Documented and used here: Event.<Name>.Subscribe, HTTPRequest, PersistentDB, Plugin.HasPermission.
-- STILL UNVERIFIED (marked ASSUMPTION): the kill-count chat wording, objType.name on loot, and
-- PlayerEntity.displayName. Enrage and killstreak have no known API, so they are never sent
-- (enrage bosses such as Telos/Amascut score every kill at 0%).

local core = require("core")
local config = require("config")
local ui = require("ui")
local collog = require("collog")
local rate_data = require("rates") -- generated by tools/gen_lua_rates.py
local killvars = require("killvars")

local M = {}
local SERVER_TICK_SECONDS = 0.6 -- Event.ServerLogic fires roughly every 600 ms

function M.start(G)
  local ticks = 0
  local base = config.api_url
  local say = G.log or print

  local host = {
    http_post = function(url, headers, body, cb)
      local req = G.HTTPRequest.new(G.Plugin.urls.api, url:sub(#base + 1))
      for k, v in pairs(headers) do req:AddHeader(k, v) end
      req:Post(body, function(r)
        -- Any HTTP response (even 4xx/5xx) reaches core with its code; transport failures report nil.
        local code = r.responseCode
        if code and code > 0 then cb(code, r.data) else cb(nil) end
      end)
    end,
    storage_get = function(k) return G.PersistentDB:GetString(k) end,
    storage_set = function(k, v) G.PersistentDB:SetString(k, v) end,
    now = function() return ticks * SERVER_TICK_SECONDS end,
    random_hex = function(n)
      local t = {}
      for i = 1, n do t[i] = string.format("%x", math.random(0, 15)) end
      return table.concat(t)
    end,
    log = function(m) say("[DropTracker] " .. m) end,
  }

  local tracker = core.new(host, config)
  local last = { boss = nil, kc = nil } -- most recent kill, so drops can be attributed
  local profile_checked = false
  local warned_http = false
  local last_pending = 0
  local last_http = nil

  -- Session stats for the friendly output (not sent anywhere). `recent` lists bosses, latest first.
  local stats, recent = {}, {}

  -- Enrage bosses (Telos, Arch-Glacor, Amascut): the player picks how they farm each one (rates.strategies) and the
  -- collection-log labels score every kill that way. The choice is kept on disk, one "boss<TAB>option" line each.
  local strategies = rate_data.strategies or {}
  local chosen = {}
  for line in (host.storage_get("strategy") or ""):gmatch("[^\n]+") do
    local group, option = line:match("^(.-)\t(.+)$")
    if group then chosen[group] = option end
  end
  local clog -- the collection-log labeller, created below

  -- The base rates with the selected option's enrage-dependent items laid over them ("off" or an unknown id adds none).
  local function effective_rates()
    local out = {}
    for boss, items in pairs(rate_data.rates) do out[boss] = items end
    for group, s in pairs(strategies) do
      local want = chosen[group] or s.default
      for _, option in ipairs(s.options) do
        if option.id == want then
          for page, items in pairs(option.rates) do
            local merged = {}
            for item, rate in pairs(out[page] or {}) do merged[item] = rate end
            for item, rate in pairs(items) do merged[item] = rate end
            out[page] = merged
          end
        end
      end
    end
    return out
  end

  local clog_ctx -- collog's context; its rates are swapped when the choice changes
  local function choose_strategy(group, option)
    chosen[group] = option
    local out = {}
    for name, id in pairs(chosen) do out[#out + 1] = name .. "\t" .. id end
    table.sort(out)
    host.storage_set("strategy", table.concat(out, "\n"))
    if clog_ctx then clog_ctx.rates = effective_rates() end
  end

  local presenter = ui.new(G, host.log, { strategies = strategies, selected = chosen, on_change = choose_strategy })

  -- Latest total kill count per boss, kept on disk. The collection-log dry % needs it for any boss with a known
  -- rate, tracked (sent to the server) or not, so it is recorded for every kill message that names such a boss.
  local boss_kc = {}
  for line in (host.storage_get("boss_kc") or ""):gmatch("[^\n]+") do
    local name, n = line:match("^(.-)\t(%d+)$")
    if name then boss_kc[name] = tonumber(n) end
  end
  local function canonical(boss) return rate_data.aliases[boss] or boss end
  local function remember_kc(boss, kc)
    local canon = canonical(boss)
    if boss_kc[canon] == kc then return end
    boss_kc[canon] = kc
    local out = {}
    for name, n in pairs(boss_kc) do out[#out + 1] = name .. "\t" .. n end
    table.sort(out)
    host.storage_set("boss_kc", table.concat(out, "\n"))
  end

  -- Total kill count for a rates key `boss`, or failing that for a collection-log page `title`: kill messages use the
  -- NPC name ("Telos, the Warden"), the log uses short titles ("Telos"). An exact name wins; otherwise a stored name
  -- that starts with the title followed by a comma or space. (A longer title never matches a shorter name, so
  -- "Nex, Angel of Death" does not pick up plain "Nex".)
  local function kc_for(boss, title)
    local normal, hard = killvars.counts(G, boss, title) -- the game's own counts: no kill needed
    if normal then return normal, hard end
    if boss_kc[boss] then return boss_kc[boss] end
    local t = (title or ""):lower()
    if t == "" then return nil end
    local best
    for name, n in pairs(boss_kc) do
      local nl = name:lower()
      if nl == t then return n end
      if nl:sub(1, #t) == t and nl:sub(#t + 1, #t + 1):match("[, ]") and (not best or #name < #best.name) then
        best = { name = name, n = n }
      end
    end
    return best and best.n or nil
  end

  clog_ctx = {
    rates = effective_rates(),
    shared = rate_data.shared, -- items several bosses drop, scored over all their kills together
    kc_of = kc_for,
    log = host.log,
    report = function(entries) tracker.set_collection(entries) end, -- sent to the backend with the next sync
    unmatched = function(title, names) -- remembered on disk (one line per page) so coverage gaps can be reviewed
      local pages, order = {}, {}
      for line in (host.storage_get("clog_unmatched") or ""):gmatch("[^\n]+") do
        local t, list = line:match("^(.-)\t(.*)$")
        if t then pages[t] = list order[#order + 1] = t end
      end
      if pages[title] == nil and #names > 0 then order[#order + 1] = title end
      pages[title] = #names > 0 and table.concat(names, "; ") or nil -- a fully covered page is dropped
      local out = {}
      for _, t in ipairs(order) do
        if pages[t] then out[#out + 1] = t .. "\t" .. pages[t] end
      end
      host.storage_set("clog_unmatched", table.concat(out, "\n"))
    end,
  }
  clog = G.ui and G.id and G.clientConfig and collog.new(G, clog_ctx) or nil

  local function touch(boss)
    local s = stats[boss]
    if not s then s = { name = boss, kc = 0, kills = 0, drops = {}, drop_order = {} } stats[boss] = s end
    for i, n in ipairs(recent) do if n == boss then table.remove(recent, i) break end end
    table.insert(recent, 1, boss)
    return s
  end

  local function has_http()
    return G.Plugin.HasPermission(G.PluginPermissions.httpAccess)
  end

  local function refresh(show)
    local state = { http = has_http(), pending = #tracker.queue, bosses = {} }
    for _, boss in ipairs(recent) do
      local s = stats[boss]
      local drops = {}
      for _, item in ipairs(s.drop_order) do drops[#drops + 1] = { item = item, count = s.drops[item] } end
      state.bosses[#state.bosses + 1] = { name = s.name, kc = s.kc, kills = s.kills, drops = drops }
    end
    presenter.update(state, show)
  end

  -- ASSUMPTION: PlayerEntity exposes displayName (NPCEntity does, per the tutorial).
  local function player_name()
    local ok, name = pcall(function() return G.Player.GetEntity().displayName end)
    return ok and name or nil
  end

  -- The tracked-item name to report for `item_name` under `boss`, or nil if it is not one of that boss's uniques.
  local function report_name(boss, item_name)
    local rules = config.tracked[boss]
    if not rules or not item_name then return nil end
    local report = rules.items and rules.items[item_name]
    if report then return report end
    for _, pat in ipairs(rules.patterns or {}) do
      if item_name:find(pat) then return item_name end
    end
  end

  local seen = {} -- boss|item|kc already recorded: the loot event and the news line can both report one drop
  local function record_drop(boss, report, quantity, kc)
    local key = boss .. "|" .. report .. "|" .. tostring(kc)
    if seen[key] then return end
    seen[key] = true
    tracker.on_drop(boss, report, quantity, kc)
    local s = touch(boss)
    if not s.drops[report] then s.drops[report] = 0 s.drop_order[#s.drop_order + 1] = report end
    s.drops[report] = s.drops[report] + 1
    presenter.notify(ui.drop_line(boss, report))
    refresh(true)
  end

  local function norm(s) return (tostring(s):lower():gsub("[^%w]", "")) end

  -- The game announces unique drops in chat ("News: <you> has received <item> drop at <kc> kills!").
  -- The boss is not named, so find it from the item. Other players' announcements are ignored.
  local function handle_news(text)
    for _, pattern in ipairs(config.drop_patterns) do
      local who, item, kc = text:match(pattern)
      if who then
        kc = tonumber((kc:gsub(",", "")))
        local me = player_name()
        if me and me ~= "" then
          if norm(who) ~= norm(me) then return true end
        elseif not (last.kc and kc == last.kc) then
          return true -- cannot verify the name, so only trust a drop at our own latest kill count
        end
        local boss = last.boss and report_name(last.boss, item) and last.boss
        if not boss then
          for name in pairs(config.tracked) do
            if report_name(name, item) then boss = name break end
          end
        end
        local report = boss and report_name(boss, item)
        if report and kc then record_drop(boss, report, 1, kc) end
        return true
      end
    end
  end

  local function handle_chat(text)
    text = text:gsub("<[^>]*>", "") -- strip <col=..> / <br> / <img=..> markup
    if handle_news(text) then return end
    for _, rule in ipairs(config.kill_patterns) do
      local a, b = text:match(rule.pattern)
      local boss, kc = a, b
      if rule.kc_first then boss, kc = b, a end
      if boss then
        kc = tonumber((kc:gsub(",", "")))
        if kc then
          remember_kc(boss, kc)
          local warning = killvars.check(G, boss, kc)
          if warning then host.log(warning) end
        end
        if config.tracked[boss] and kc then
          last.boss, last.kc = boss, kc
          tracker.on_kill(boss, kc) -- no enrage/streak source in the public API
          local s = touch(boss)
          s.kc, s.kills = kc, s.kills + 1
          presenter.notify(ui.kill_line(boss, kc, s.kills))
          refresh(true)
        end
        return
      end
    end
  end

  local function handle_loot(item_name, quantity)
    if not last.boss then return end
    local report = report_name(last.boss, item_name)
    if report then record_drop(last.boss, report, quantity, last.kc) end
  end

  local function sync_profile()
    if profile_checked or not G.Player.IsAvailable() then return end
    local name = player_name()
    if not name or name == "" then return end
    profile_checked = true
    if config.publish_to_website then
      tracker.set_profile(name, true)
    elseif tracker.profile and tracker.profile.public then
      tracker.set_profile(name, false) -- revoke an earlier opt-in
    end
  end

  refresh(false)

  G.Event.ChatMessage.Subscribe("dropTrackerChat", function(e) handle_chat(e.chatMessage) end)

  -- ASSUMPTION: loot appears as an object stack owned by the player; objType.name is the item name.
  G.Event.ObjStackEntityAdded.Subscribe("dropTrackerLoot", function(e)
    if e.isOwner and e.objType then handle_loot(e.objType.name, e.count) end
  end)

  G.Event.ServerLogic.Subscribe("dropTrackerTick", function()
    ticks = ticks + 1
    if clog then clog.tick() end
    sync_profile()
    local http = has_http()
    if http then -- nothing is sent until the player grants httpAccess
      tracker.tick()
    elseif not warned_http then
      warned_http = true
      host.log("httpAccess is not granted, so nothing will be sent")
    end
    if http ~= last_http then -- also covers grants that do not raise OptionalPermissionChanged
      if last_http ~= nil then host.log("httpAccess is now " .. (http and "granted" or "revoked")) end
      last_http = http
      refresh(false)
    end
    -- keep the sync status current: when the queue changes, and otherwise about every 3 s (permission changes)
    if #tracker.queue ~= last_pending or ticks % 5 == 0 then
      last_pending = #tracker.queue
      refresh(false)
    end
  end)

  -- Shows up in the console when a permission is granted/revoked (ppe/ppd or the Hub) while the plugin runs.
  G.Event.OptionalPermissionChanged.Subscribe("dropTrackerPerm", function(e)
    host.log("permission " .. tostring(e.permissionName) .. " enabled = " .. tostring(e.enabled))
    refresh(false)
  end)

  -- Called from PluginShutdown so a reload does not leave the old window behind.
  local app = {}
  function app.shutdown()
    for _, name in ipairs({ "ChatMessage", "ObjStackEntityAdded", "ServerLogic", "OptionalPermissionChanged" }) do
      pcall(function() G.Event[name].Unsubscribe(({
        ChatMessage = "dropTrackerChat", ObjStackEntityAdded = "dropTrackerLoot",
        ServerLogic = "dropTrackerTick", OptionalPermissionChanged = "dropTrackerPerm",
      })[name]) end)
    end
    presenter.destroy()
    if clog then clog.shutdown() end
  end
  return app
end

return M
